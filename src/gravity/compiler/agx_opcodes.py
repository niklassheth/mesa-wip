opcodes = {}
immediates = {}

VARIABLE = ~0

class Opcode(object):
   def __init__(self, name, dests, srcs, imms, is_float, can_eliminate,
                can_reorder, schedule_class):
      self.name = name
      self.dests = dests if dests != VARIABLE else 0
      self.srcs = srcs if srcs != VARIABLE else 0
      self.variable_srcs = (srcs == VARIABLE)
      self.variable_dests = (dests == VARIABLE)
      self.imms = imms
      self.is_float = is_float
      self.can_eliminate = can_eliminate
      self.can_reorder = can_reorder
      self.schedule_class = schedule_class

class Immediate(object):
   def __init__(self, name, ctype):
      self.name = name
      self.ctype = ctype

def op(name, dests = 1, srcs = 0, imms = [], is_float = False,
        can_eliminate = True, can_reorder = True, schedule_class = "none"):
   opcodes[name] = Opcode(name, dests, srcs, imms, is_float, can_eliminate,
                          can_reorder, schedule_class)

def immediate(name, ctype = "uint32_t"):
   imm = Immediate(name, ctype)
   immediates[name] = imm
   return imm

FORMAT = immediate("format", "enum agx_format")
IMM = immediate("imm", "uint64_t")
SHIFT = immediate("shift")
MASK = immediate("mask")

# Shared RA/spill IR opcodes used by Gravity and its RA unit tests.
op("mov", srcs = 1)
op("mov_imm", imms = [IMM])

op("collect", srcs = VARIABLE)
op("split", srcs = 1, dests = VARIABLE)
op("phi", srcs = VARIABLE, schedule_class = "preload")

# The srcs double as destinations. Only deals in registers. Generated by
# parallel copy lowering and lowered soon after; kept as an opcode for RA
# validation.
op("swap", dests = 0, srcs = 2)

# Like mov, but takes a register and can only appear at the start. Guaranteed
# to be coalesced during RA, rather than lowered to a real move.
op("preload", srcs = 1, schedule_class = "preload")

# Opposite of preload. Exports a scalar value to a particular register at the
# end of the shader part. Must only appear after the logical end of the exit
# block.
op("export", dests = 0, srcs = 1, imms = [IMM], can_eliminate = False,
   schedule_class = "invalid")

# Spill lowering opcodes (exercised by agx_lower_spill and unit tests).
op("stack_load", srcs = 1, imms = [FORMAT, MASK], can_reorder = False,
   schedule_class = "load")
op("stack_store", dests = 0, srcs = 2, imms = [FORMAT, MASK],
   can_eliminate = False, schedule_class = "store")

# Allocation IR for target-selected Apple9 instructions. Encoding remains in
# the Apple9 backend; common SSA and allocation passes see explicit dataflow.
op("apple9", dests = VARIABLE, srcs = VARIABLE, can_eliminate = False, can_reorder = False)
op("apple9_pure", dests = VARIABLE, srcs = VARIABLE, can_eliminate = True, can_reorder = False)
op("apple9_cf", dests = 0, srcs = VARIABLE, can_eliminate = False, can_reorder = False)

# Synthetic ALU/sink opcodes used by shared RA and SSA-repair unit tests.
op("iadd", srcs = 2, imms = [SHIFT])
op("fadd", srcs = 2, is_float = True)
op("unit_test", dests = 0, srcs = 1, can_eliminate = False)
